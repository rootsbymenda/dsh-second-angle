/**
 * Full-loop tests: the REAL harness agent loop (published @deepseek-ai/dsh-agent-loop),
 * a real tool, real Sessions, and the real `agent/turn-stopping` dispatch drive the
 * plugin; only the two models (the turn's and the auditor's) are scripted.
 */
import { afterEach, describe, expect, it } from 'vitest'
import { Context } from '@deepseek-ai/cordis'
import type { Agent } from '@deepseek-ai/dsh-agent'
import AgentLoop from '@deepseek-ai/dsh-agent-loop'
import { mountAgentLoopTestDependencies } from '@deepseek-ai/dsh-agent-loop-testkit'
import { createUserMessage } from '@deepseek-ai/dsh-llm'
import { pluginRecordOf, SessionId, type SessionEvent } from '@deepseek-ai/dsh-session'
import { defineContentToolFixture } from '@deepseek-ai/dsh-tools'
import * as SecondAngle from '../src/index.ts'
import type { VerdictRecord } from '../src/plugin.ts'
import { ScriptedAdapter, textReply, toolReply, type ScriptEntry } from './helpers/scripted-adapter.ts'

const FACTS = [
  'inventory report',
  'entries: 4',
  'build: passed',
  'owner: platform team',
  'generated by the nightly job; this file lists the entries of the current release only, not older releases.',
  'checksum and signature lines follow in the full report; they are omitted from this summary view.',
].join('\n')

const contexts: Context[] = []
afterEach(async () => {
  for (const ctx of contexts.splice(0)) await ctx.fiber.dispose()
})

/** Mount the loop, a facts tool, the two scripted models, and the plugin; create one Agent. */
async function setup(main: ScriptEntry[], auditor: ScriptEntry[], config: Record<string, unknown> = {}, reasoning?: ConstructorParameters<typeof ScriptedAdapter>[1]) {
  const ctx = new Context()
  contexts.push(ctx)
  await mountAgentLoopTestDependencies(ctx)
  await ctx.plugin(AgentLoop, { agents: [] })
  ctx.tools.register(defineContentToolFixture({
    name: 'read_facts', description: 'Read the facts file.', parameters: {},
    async execute() { return [{ type: 'text', text: FACTS }] },
  }))
  const mainModel = new ScriptedAdapter(main)
  const auditModel = new ScriptedAdapter(auditor, reasoning)
  ctx.llm.registerAdapter(['mock'], mainModel)
  ctx.llm.registerAdapter(['audit'], auditModel)
  await ctx.plugin(SecondAngle, { auditorProvider: 'audit', auditorModel: 'auditor', ...config })
  const agent = await ctx.agentLoop.create(SessionId(`s-${String(contexts.length)}`), { provider: 'mock', model: 'main' })
  return { ctx, agent, mainModel, auditModel }
}

async function ask(agent: Agent, text: string): Promise<void> {
  agent.followup(createUserMessage({ content: [{ type: 'text', text }], source: { kind: 'user' } }))
  await agent.whenIdle()
}

function events(agent: Agent): readonly SessionEvent[] {
  return agent.session.snapshotEvents()
}

function verdicts(agent: Agent): VerdictRecord[] {
  return events(agent).flatMap((event) => {
    const record = pluginRecordOf(event)
    return record?.type === 'plugin:second-angle/verdict' ? [record.data as VerdictRecord] : []
  })
}

function secondAngleMessages(agent: Agent): SessionEvent[] {
  return events(agent).filter(event => event.type === 'user/message' && (event.data.source as { kind: string }).kind === 'second-angle')
}

function count(agent: Agent, type: string): number {
  return events(agent).filter(event => event.type === type).length
}

function lastAssistantText(agent: Agent): string {
  const messages = events(agent).filter(event => event.type === 'assistant/message')
  const last = messages.at(-1)
  if (last?.type !== 'assistant/message') return ''
  return last.data.message.content.flatMap(block => block.type === 'text' ? [block.text] : []).join('')
}

async function waitFor(predicate: () => boolean, timeoutMs = 3000): Promise<void> {
  const deadline = Date.now() + timeoutMs
  while (!predicate()) {
    if (Date.now() > deadline) throw new Error('waitFor: condition not met')
    await new Promise(resolve => setTimeout(resolve, 10))
  }
}

const audit = (claims: object[]): ScriptEntry => textReply(JSON.stringify({ claims }))
const contradiction = { claim: 'The facts file lists 3 entries', evidence_quote: 'entries: 4', label: 'CONTRADICTED', reason: 'the output says 4' }

describe('sync mode: contradiction steers a correction in the same turn', () => {
  it('steers once, the model revises in the same turn, and the turn is audited once', async () => {
    const { agent, mainModel, auditModel } = await setup(
      [toolReply('c1', 'read_facts', {}), textReply('The facts file lists 3 entries.'), textReply('Correction: the facts file lists 4 entries.')],
      [audit([contradiction]), audit([contradiction])],
    )
    await ask(agent, 'How many entries are in the facts file?')
    expect(mainModel.requests).toHaveLength(3)
    expect(auditModel.requests).toHaveLength(1)
    // Dedupe: the second scripted verdict was never requested although the hook fired again.
    expect(auditModel.remaining).toBe(1)
    expect(count(agent, 'turn/end')).toBe(1)
    expect(lastAssistantText(agent)).toBe('Correction: the facts file lists 4 entries.')
    const steer = secondAngleMessages(agent)
    expect(steer).toHaveLength(1)
    const source = steer[0]?.data as { source: { kind: string; form: string; summary: string }; content: { text: string }[] }
    expect(source.source).toMatchObject({ kind: 'second-angle', form: 'notice' })
    expect(source.source.summary).toContain('1 claim contradicted')
    expect(source.content[0]?.text).toContain('The tool output shows: "entries: 4"')
    // The correction reached the model as part of the revision request.
    expect(JSON.stringify(mainModel.requests[2]?.messages)).toContain('Second angle: your answer above contradicts')
    const [verdict] = verdicts(agent)
    expect(verdict).toMatchObject({ status: 'steered', source: 'auditor', mode: 'sync', delivered: ['steer'] })
    expect(verdict?.claims?.[0]).toMatchObject({ label: 'CONTRADICTED', quoteFound: true })
  })

  it('flags instead of steering when the cited contradiction is not in the evidence', async () => {
    const { agent, mainModel } = await setup(
      [toolReply('c1', 'read_facts', {}), textReply('The facts file lists 3 entries.')],
      [audit([{ ...contradiction, evidence_quote: 'entries: 9' }])],
    )
    await ask(agent, 'How many entries?')
    expect(mainModel.requests).toHaveLength(2)
    expect(secondAngleMessages(agent)).toHaveLength(0)
    expect(verdicts(agent)[0]).toMatchObject({ status: 'flagged', delivered: ['log'] })
  })
})

describe('sync mode: flags, clean turns, and the auditor request', () => {
  it('flags unsupported and overstated claims without forcing another step', async () => {
    const { agent, mainModel } = await setup(
      [toolReply('c1', 'read_facts', {}), textReply('The build passed and every release ever shipped had 4 entries.')],
      [audit([
        { claim: 'The build passed', evidence_quote: 'build: passed', label: 'SUPPORTED', reason: 'shown' },
        { claim: 'every release ever shipped had 4 entries', evidence_quote: 'current release only', label: 'OVERSTATED', reason: 'only the current release is listed' },
      ])],
    )
    await ask(agent, 'Summarize the facts.')
    expect(mainModel.requests).toHaveLength(2)
    expect(count(agent, 'turn/end')).toBe(1)
    expect(secondAngleMessages(agent)).toHaveLength(0)
    expect(verdicts(agent)[0]).toMatchObject({ status: 'flagged', source: 'auditor', delivered: ['log'] })
  })

  it('records a clean turn and changes nothing', async () => {
    const { agent, mainModel } = await setup(
      [toolReply('c1', 'read_facts', {}), textReply('The facts file lists 4 entries and the build passed.')],
      [audit([{ claim: 'lists 4 entries', evidence_quote: 'entries: 4', label: 'SUPPORTED', reason: 'shown' }])],
    )
    await ask(agent, 'How many entries?')
    expect(mainModel.requests).toHaveLength(2)
    expect(verdicts(agent)[0]).toMatchObject({ status: 'clean', delivered: [] })
  })

  it('sends the method, the card, the full tool output, the output cap, and thinking off when the route offers it', async () => {
    const { agent, auditModel } = await setup(
      [toolReply('c1', 'read_facts', {}), textReply('The facts file lists 4 entries.')],
      [audit([])],
      {},
      { efforts: [{ id: 'off' as never, name: 'Off' }, { id: 'high' as never, name: 'High' }] },
    )
    await ask(agent, 'How many entries?')
    const request = auditModel.requests[0]
    expect(request?.system).toContain('FACTS AND LIMITS CARD')
    expect(JSON.stringify(request?.messages)).toContain('not older releases')
    expect(request?.maxTokens).toBe(2048)
    expect(request?.temperature).toBe(0)
    expect(request?.reasoningEffort).toBe('off')
    expect(verdicts(agent)[0]?.route).toEqual({ provider: 'audit', model: 'auditor', reasoningEffort: 'off' })
  })

  it('omits the reasoning effort when the route does not offer it', async () => {
    const { agent, auditModel } = await setup(
      [toolReply('c1', 'read_facts', {}), textReply('The facts file lists 4 entries.')],
      [audit([])],
    )
    await ask(agent, 'How many entries?')
    expect(auditModel.requests[0]?.reasoningEffort).toBeUndefined()
  })
})

describe('gates', () => {
  it('a turn that read nothing never reaches the model; its absolute words become a scanner flag', async () => {
    const { agent, auditModel } = await setup([textReply('Nobody has ever measured this before.')], [])
    await ask(agent, 'Has anyone measured it?')
    expect(auditModel.requests).toHaveLength(0)
    expect(verdicts(agent)[0]).toMatchObject({ status: 'flagged', source: 'scanner', delivered: ['log'] })
  })

  it('skips a no-tool answer without markers, and records the gate when asked to', async () => {
    const { agent, auditModel } = await setup([textReply('Here is a short plan for the refactor you asked about.')], [], { recordSkips: true })
    await ask(agent, 'Plan the refactor.')
    expect(auditModel.requests).toHaveLength(0)
    expect(verdicts(agent)[0]).toMatchObject({ status: 'skipped', detail: 'no-tool-no-markers' })
  })

  it('skips a tool turn whose answer the scanner finds clean when the output is too thin to check', async () => {
    const { agent, auditModel } = await setup(
      [toolReply('c1', 'read_facts', {}), textReply('I read the facts file for you.')],
      [], { minEvidenceChars: 5000, recordSkips: true },
    )
    await ask(agent, 'Read it.')
    expect(auditModel.requests).toHaveLength(0)
    expect(verdicts(agent)[0]).toMatchObject({ status: 'skipped', detail: 'scanner-clean-thin-evidence' })
  })

  it('does nothing at all when disabled', async () => {
    const { agent, auditModel } = await setup([toolReply('c1', 'read_facts', {}), textReply('Nobody knows; 3 entries.')], [], { enabled: false })
    await ask(agent, 'How many?')
    expect(auditModel.requests).toHaveLength(0)
    expect(verdicts(agent)).toHaveLength(0)
  })
})

describe('fails open', () => {
  it('records no-verdict when the auditor answers in prose, and the turn completes unchanged', async () => {
    const { agent, mainModel } = await setup(
      [toolReply('c1', 'read_facts', {}), textReply('The facts file lists 3 entries.')],
      [textReply('I am not sure about these claims.')],
    )
    await ask(agent, 'How many entries?')
    expect(mainModel.requests).toHaveLength(2)
    expect(count(agent, 'turn/end')).toBe(1)
    expect(verdicts(agent)[0]).toMatchObject({ status: 'no-verdict', source: 'none' })
  })

  it('records an error when the auditor provider fails, and the turn completes', async () => {
    const { agent } = await setup([toolReply('c1', 'read_facts', {}), textReply('The facts file lists 3 entries.')], ['throw'])
    await ask(agent, 'How many entries?')
    const end = events(agent).find(event => event.type === 'turn/end')
    expect(end?.type === 'turn/end' ? end.data.reason.kind : undefined).toBe('completed')
    expect(verdicts(agent)[0]).toMatchObject({ status: 'error' })
  })

  it('abandons an auditor that does not answer within maxLatencyMs', async () => {
    const { agent } = await setup([toolReply('c1', 'read_facts', {}), textReply('The facts file lists 3 entries.')], ['hang'], { maxLatencyMs: 150 })
    const started = Date.now()
    await ask(agent, 'How many entries?')
    expect(Date.now() - started).toBeLessThan(5000)
    expect(verdicts(agent)[0]).toMatchObject({ status: 'timeout', detail: 'no verdict within 150 ms' })
  })

  it('falls back to the scanner\'s absolute words when the auditor gives no verdict', async () => {
    const { agent } = await setup([toolReply('c1', 'read_facts', {}), textReply('Nobody has more than 3 entries.')], [textReply('')])
    await ask(agent, 'How many entries?')
    expect(verdicts(agent)[0]).toMatchObject({ status: 'no-verdict', source: 'scanner', delivered: ['log'] })
  })
})

describe('notices are delivered after the turn closes', () => {
  it('a flag notice never forces a step; it waits in the inbox and reaches the model with the next turn', async () => {
    const { agent, mainModel } = await setup(
      [toolReply('c1', 'read_facts', {}), textReply('Every release had 4 entries.'), textReply('Noted.')],
      [audit([{ claim: 'Every release had 4 entries', evidence_quote: 'current release only', label: 'OVERSTATED', reason: 'one release shown' }])],
      { flagNotice: true },
    )
    await ask(agent, 'Summarize.')
    expect(mainModel.requests).toHaveLength(2)
    await waitFor(() => agent.inbox.nextStep.length === 1)
    expect(agent.inbox.nextStep[0]?.source.kind).toBe('second-angle')
    expect(verdicts(agent)[0]).toMatchObject({ status: 'flagged', delivered: ['log', 'notice'] })
    await ask(agent, 'Thanks.')
    expect(JSON.stringify(mainModel.requests[2]?.messages)).toContain('Second angle on your answer in turn')
  })
})

describe('async mode', () => {
  it('lets the turn close first and attaches the verdict later; a contradiction becomes a notice', async () => {
    const { agent, mainModel } = await setup(
      [toolReply('c1', 'read_facts', {}), textReply('The facts file lists 3 entries.')],
      [{ delayMs: 50, chunks: audit([contradiction]) as never }],
      { mode: 'async' },
    )
    await ask(agent, 'How many entries?')
    expect(mainModel.requests).toHaveLength(2)
    expect(count(agent, 'turn/end')).toBe(1)
    await waitFor(() => verdicts(agent).length === 1)
    expect(verdicts(agent)[0]).toMatchObject({ status: 'flagged', mode: 'async', delivered: ['log', 'notice'] })
    await waitFor(() => agent.inbox.nextStep.length === 1)
  })

  it('with asyncContradicted=followup, a contradiction starts a correction turn', async () => {
    const { agent, mainModel } = await setup(
      [toolReply('c1', 'read_facts', {}), textReply('The facts file lists 3 entries.'), textReply('You are right: 4 entries.')],
      [{ delayMs: 20, chunks: audit([contradiction]) as never }],
      { mode: 'async', asyncContradicted: 'followup' },
    )
    await ask(agent, 'How many entries?')
    await waitFor(() => count(agent, 'turn/end') === 2)
    await agent.whenIdle()
    expect(mainModel.requests).toHaveLength(3)
    expect(lastAssistantText(agent)).toBe('You are right: 4 entries.')
    expect(verdicts(agent)[0]).toMatchObject({ status: 'steered', delivered: ['followup'] })
  })
})
